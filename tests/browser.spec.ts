test('existing demo questions, answers and bookmarks survive code migration', async ({ page }) => {
  const oldId = 'abcdefab-1234-4234-8234-123456789abc'
  await page.addInitScript((id) => {
    if (localStorage.getItem('dheepask-demo-v1')) return
    localStorage.setItem('dheepask-demo-v1', JSON.stringify({ questions: [{ id, title: 'Pertanyaan lama yang tetap tersimpan', body: 'Konteks lama', category: 'Random', created_at: new Date().toISOString(), answer_count: 1 }], answers: [{ id: 'old-answer', question_id: id, body: 'Jawaban lama tetap utuh', created_at: new Date().toISOString() }] }))
    localStorage.setItem('dheepask-bookmarks', JSON.stringify([id]))
  }, oldId)
  await page.goto(`/questions/${oldId}`)
  await expect(page.getByText('Jawaban lama tetap utuh')).toBeVisible()
  await expect(page.getByTestId('question-code')).toHaveText(/^[A-Z]{5}$/)
  const code = await page.getByTestId('question-code').innerText()
  await expect(page.getByRole('button', { name: 'Simpan pertanyaan' })).toHaveAttribute('aria-pressed', 'true')
  await page.goto(`/${code.toLowerCase()}`)
  await expect(page.getByText('Jawaban lama tetap utuh')).toBeVisible()
  await expect(page.getByTestId('question-code')).toHaveText(code)
})
