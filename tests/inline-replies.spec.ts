test('question reactions work without expanding, persist between feed and conversation, and synchronize across tabs', async ({ page, context }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const card = page.locator('.question-card').filter({ hasText: 'Apa hal kecil yang belakangan ini bikin kamu merasa bahagia?' })
  const reactions = card.getByRole('group', { name: 'Reaksi pertanyaan', exact: true })
  await chooseEmoji(page, reactions, 'cat', '🐈')
  await chooseEmoji(page, reactions, 'coffee', '☕')
  await expect(reactions.getByRole('button', { name: 'Reaksi 🐈, 1', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(reactions.getByRole('button', { name: 'Reaksi ☕, 1', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(card.locator('[data-answer-id]')).toHaveCount(0)
  await page.goto('/KTMXZ')
  const conversationReactions = page.getByRole('group', { name: 'Reaksi pertanyaan', exact: true })
  await expect(conversationReactions.getByRole('button', { name: 'Reaksi 🐈, 1', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const answerReactions = page.locator('[data-answer-id="demo-a1"]').getByRole('group', { name: 'Reaksi jawaban', exact: true })
  await expect(answerReactions.getByRole('button', { name: /^Reaksi / })).toHaveCount(0)
  await page.getByLabel('Jawaban anonim', { exact: true }).fill('Draft saat pertanyaan mendapat reaction')
  const writer = await context.newPage()
  await writer.goto('/')
  const otherCard = writer.locator('.question-card').filter({ hasText: 'Apa hal kecil yang belakangan ini bikin kamu merasa bahagia?' })
  await chooseEmoji(writer, otherCard.getByRole('group', { name: 'Reaksi pertanyaan', exact: true }), 'pizza', '🍕')
  await expect(conversationReactions.getByRole('button', { name: 'Reaksi 🍕, 1', exact: true })).toBeVisible()
  await expect(page.getByLabel('Jawaban anonim', { exact: true })).toHaveValue('Draft saat pertanyaan mendapat reaction')
  await conversationReactions.getByRole('button', { name: 'Reaksi 🐈, 1', exact: true }).click()
  await expect(otherCard.getByRole('button', { name: 'Reaksi 🐈, 1', exact: true })).toHaveCount(0)
  await writer.close()
  await page.reload()
  await expect(conversationReactions.getByRole('button', { name: 'Reaksi ☕, 1', exact: true })).toBeVisible()
  await expect(conversationReactions.getByRole('button', { name: 'Reaksi 🍕, 1', exact: true })).toBeVisible()
  await expect(conversationReactions.getByRole('button', { name: 'Reaksi 🐈, 1', exact: true })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('emoji picker closes with Escape or an outside click, supports keyboard selection and preserves legacy reactions', async ({ page, context }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/KTMXZ')
  const root = page.locator('[data-answer-id="demo-a1"]')
  const add = root.getByRole('button', { name: 'Tambah reaction', exact: true })
  await add.click()
  const dialog = page.getByRole('dialog', { name: 'Pilih reaction emoji' })
  await dialog.getByPlaceholder('Cari emoji').fill('cat')
  const bounds = await dialog.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
  expect(bounds!.y).toBeGreaterThanOrEqual(0)
  expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(844)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(add).toBeFocused()
  await add.click()
  await dialog.getByPlaceholder('Cari emoji').fill('coffee')
  await expect(dialog.getByRole('button', { name: '☕', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.keyboard.press('Enter')
  await expect(dialog).toHaveCount(0)
  await expect(root.getByRole('button', { name: 'Reaksi ☕, 1', exact: true })).toBeVisible()
  await add.click()
  await dialog.getByPlaceholder('Cari emoji').fill('zzzzzz-no-emoji')
  await expect(dialog.getByText('Emoji tidak ditemukan', { exact: true })).toBeVisible()
  await page.getByRole('heading', { level: 1 }).click()
  await expect(dialog).toHaveCount(0)
  const writer = await context.newPage()
  await writer.goto('/KTMXZ')
  await page.getByLabel('Jawaban anonim', { exact: true }).fill('Draft saat reaction masuk dari tab lain')
  await chooseEmoji(writer, writer.locator('[data-answer-id="demo-a1"]'), 'pizza', '🍕')
  await expect(root.getByRole('button', { name: 'Reaksi 🍕, 1', exact: true })).toBeVisible()
  await expect(page.getByLabel('Jawaban anonim', { exact: true })).toHaveValue('Draft saat reaction masuk dari tab lain')
  await writer.close()
  await page.evaluate(() => {
    const saved = JSON.parse(localStorage.getItem('dheepask-demo-v1')!)
    saved.answerReactions['demo-a1'] = { counts: { heart: 3 }, mine: 'heart' }
    localStorage.setItem('dheepask-demo-v1', JSON.stringify(saved))
  })
  await page.reload()
  const heart = root.getByRole('button', { name: 'Reaksi ❤️, 3', exact: true })
  await expect(heart).toHaveAttribute('aria-pressed', 'true')
  await heart.click()
  await expect(root.getByRole('button', { name: 'Reaksi ❤️, 2', exact: true })).toHaveAttribute('aria-pressed', 'false')
})
