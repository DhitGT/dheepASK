alter table public.answer_reactions drop constraint answer_reactions_reaction_check;
alter table public.answer_reactions drop constraint answer_reactions_pkey;
update public.answer_reactions set reaction = case reaction
  when 'heart' then '❤️' when 'laugh' then '😂' when 'fire' then '🔥'
  when 'clap' then '👏' when 'wow' then '🤯' when 'love' then '😍' else reaction end;
alter table public.answer_reactions add primary key (answer_id,author_id,reaction);
alter table public.answer_reactions add constraint answer_reactions_emoji_fk
  foreign key (reaction) references public.reaction_emojis(emoji);

create or replace function public.get_answer_reactions(question uuid) returns jsonb
language sql stable security definer set search_path = '' as $$
  select coalesce(jsonb_object_agg(a.id, jsonb_build_object(
    'counts', (select coalesce(jsonb_object_agg(t.reaction,t.total),'{}'::jsonb)
      from (select r.reaction,count(*)::integer as total from public.answer_reactions r
        where r.answer_id = a.id group by r.reaction) t),
    'mine', (select coalesce(jsonb_agg(r.reaction order by r.reaction),'[]'::jsonb)
      from public.answer_reactions r where r.answer_id = a.id and r.author_id = auth.uid())
  )), '{}'::jsonb)
  from public.answers a join public.questions q on q.id = a.question_id
  where q.id = question and (q.room_id is null or public.is_room_member(q.room_id));
$$;
-- The obsolete single-choice endpoint must not erase other emoji choices.
drop function public.set_answer_reaction(uuid,text);
create function public.set_answer_emoji_reaction(target uuid, emoji text, selected boolean) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare question uuid; scope uuid; who uuid := auth.uid();
begin
  if who is null then raise exception 'Session required'; end if;
  if emoji is null or selected is null or not exists (select 1 from public.reaction_emojis e where e.emoji = $2) then
    raise exception 'Invalid emoji reaction';
  end if;
  select q.id,q.room_id into question,scope from public.answers a
    join public.questions q on q.id = a.question_id where a.id = target;
  if not found or (scope is not null and not public.is_room_member(scope)) then
    raise exception 'Answer not available';
  end if;
  perform pg_advisory_xact_lock(hashtextextended(target::text || who::text, 0));
  if selected then
    insert into public.answer_reactions(answer_id,author_id,reaction) values(target,who,emoji)
      on conflict do nothing;
  else
    delete from public.answer_reactions r where r.answer_id = target and r.author_id = who and r.reaction = emoji;
  end if;
  return public.get_answer_reactions(question) -> target::text;
end;
$$;
revoke all on function public.set_answer_emoji_reaction(uuid,text,boolean) from public, anon;
grant execute on function public.set_answer_emoji_reaction(uuid,text,boolean) to authenticated;
notify pgrst, 'reload schema';
commit;
